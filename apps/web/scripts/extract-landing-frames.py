"""Turn the landing video into the scroll-scrubbed frame sequence (Faz 8, D-028).

Usage (from the repo root, needs Python with Pillow and imageio-ffmpeg):

    python apps/web/scripts/extract-landing-frames.py path/to/video.mp4 --end 6.875 --fps 15

Writes
  apps/web/public/landing/frames/wide/f-000.webp …  (1280 × 720, landscape screens)
  apps/web/public/landing/frames/tall/f-000.webp …  (405 × 720 centre crop, portrait phones)
  apps/web/src/lib/landing-frames.ts                 (frame count and sizes for the hero)

`--end` cuts the clip before anything we must not show (D-028: the device screen with an invented
dashboard starts at 7.0 s in the current video). Audio is dropped.
"""

from __future__ import annotations

import argparse
import pathlib
import shutil
import subprocess
import tempfile

import imageio_ffmpeg
from PIL import Image

WEB = pathlib.Path(__file__).resolve().parent.parent
OUT = WEB / "public" / "landing" / "frames"
TS = WEB / "src" / "lib" / "landing-frames.ts"
WIDE = (1280, 720)
TALL_W = 405  # 9:16 centre crop of a 720 px high frame


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("video", type=pathlib.Path)
    parser.add_argument("--start", type=float, default=0.0)
    parser.add_argument("--end", type=float, required=True)
    parser.add_argument("--fps", type=float, default=15)
    parser.add_argument("--quality", type=int, default=85)
    args = parser.parse_args()

    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(
            [
                imageio_ffmpeg.get_ffmpeg_exe(),
                "-hide_banner",
                "-loglevel",
                "error",
                "-ss",
                str(args.start),
                "-to",
                str(args.end),
                "-i",
                str(args.video),
                "-an",
                "-vf",
                f"fps={args.fps},scale={WIDE[0]}:{WIDE[1]}:flags=lanczos",
                str(pathlib.Path(tmp) / "f-%03d.png"),
            ],
            check=True,
        )
        frames = sorted(pathlib.Path(tmp).glob("f-*.png"))
        for sub in ("wide", "tall"):
            shutil.rmtree(OUT / sub, ignore_errors=True)
            (OUT / sub).mkdir(parents=True)
        wide_bytes = tall_bytes = 0
        for index, path in enumerate(frames):
            image = Image.open(path).convert("RGB")
            name = f"f-{index:03d}.webp"
            image.save(OUT / "wide" / name, "WEBP", quality=args.quality, method=6)
            left = (WIDE[0] - TALL_W) // 2
            image.crop((left, 0, left + TALL_W, WIDE[1])).save(
                OUT / "tall" / name, "WEBP", quality=args.quality, method=6
            )
            wide_bytes += (OUT / "wide" / name).stat().st_size
            tall_bytes += (OUT / "tall" / name).stat().st_size

    TS.write_text(
        "// Generated by scripts/extract-landing-frames.py. Do not edit by hand.\n"
        "export const LANDING_FRAMES = {\n"
        f"  count: {len(frames)},\n"
        f"  fps: {args.fps:g},\n"
        f"  wide: {{ width: {WIDE[0]}, height: {WIDE[1]}, path: \"/landing/frames/wide\" }},\n"
        f"  tall: {{ width: {TALL_W}, height: {WIDE[1]}, path: \"/landing/frames/tall\" }},\n"
        "} as const;\n\n"
        "export const frameSrc = (set: \"wide\" | \"tall\", index: number) =>\n"
        "  `${LANDING_FRAMES[set].path}/f-${String(index).padStart(3, \"0\")}.webp`;\n",
        encoding="utf-8",
    )
    print(
        f"{len(frames)} frames, wide {wide_bytes / 1e6:.1f} MB, tall {tall_bytes / 1e6:.1f} MB"
    )


if __name__ == "__main__":
    main()
